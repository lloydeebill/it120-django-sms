def parse_positive_int(raw_value, default: int = 10) -> int:
    """Parse a positive integer (> 0), returning default when missing, blank, invalid, zero, or negative."""
    if raw_value is None:
        return default
    try:
        parsed = int(str(raw_value).strip())
    except (TypeError, ValueError):
        return default
    return parsed if parsed > 0 else default


